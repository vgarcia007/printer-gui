def normalize_language(value: str | None) -> str:
    language = (value or "en").strip().lower()
    return language if language in SUPPORTED_LANGUAGES else "en"


def catalog(language: str) -> dict[str, str]:
    return GERMAN_TRANSLATIONS if normalize_language(language) == "de" else {}


def translate(message: str, language: str, **values: object) -> str:
    translations = catalog(language)
    translated = translations.get(message)
    if translated is None:
        translated = message
        for prefix in ("Missing OCR tools: ",):
            if message.startswith(prefix) and prefix in translations:
                translated = translations[prefix] + message.removeprefix(prefix)
                break
    return translated.format(**values) if values else translated


def gettext(message: str, **values: object) -> str:
    return translate(message, current_app.config["UI_LANGUAGE"], **values)
